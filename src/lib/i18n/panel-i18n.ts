export function normalizeLocale(raw: string | null | undefined): PanelLocale {
  const code = String(raw ?? "en").trim().toLowerCase().replace("_", "-");
  const short = code.slice(0, 2);
  if (LOCALE_CODES.has(code)) return code as PanelLocale;
  if (LOCALE_CODES.has(short)) return short as PanelLocale;
  if (code.startsWith("pt")) return "pt";
  if (code.startsWith("zh")) return "en";
  return "en";
}

export function isRtlLocale(locale: PanelLocale): boolean {
  return locale === "ar";
}

export function t(locale: PanelLocale, key: string): string {
  if (locale === "en") return EN[key] ?? key;
  return OVERLAYS[locale]?.[key] ?? EN[key] ?? key;
}

export function applyDocumentLocale(locale: PanelLocale) {
  if (typeof document === "undefined") return;
  document.documentElement.lang = locale;
  document.documentElement.dir = isRtlLocale(locale) ? "rtl" : "ltr";
}

export function setPanelLocale(code: PanelLocale) {
  const locale = normalizeLocale(code);
  if (typeof localStorage !== "undefined") {
    localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  }
  applyDocumentLocale(locale);
  if (typeof window !== "undefined") {
    window.dispatchEvent(new CustomEvent(LOCALE_CHANGE_EVENT, { detail: locale }));
  }
}

export function readStoredLocale(): PanelLocale {
  if (typeof localStorage === "undefined") return "en";
  return normalizeLocale(localStorage.getItem(LOCALE_STORAGE_KEY));
}
